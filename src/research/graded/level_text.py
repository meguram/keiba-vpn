def describe(tid: str, level: str) -> tuple[str, bool]:
    """(文, fallback)。fallback=True は雛形で読めなかった（型の名前と水準を並べただけ）。"""
    t = CAT.BY_ID.get(tid)
    name = t.name if t else tid
    tail = "（当日）" if t is not None and t.day_of else ""
    lv = str(level)
    if lv == UNKNOWN:
        return f"{name}が分からない馬{tail}", False
    if lv == PREV_FOREIGN:
        return f"前走が海外・地方のレースだった馬{tail}", False
    tpl = TEMPLATES.get(tid)
    parts = [p.strip() for p in lv.split("×")] if tpl and len(tpl) > 1 else [lv.strip()]
    if tpl and len(parts) == len(tpl):
        cl = [f(p) for f, p in zip(tpl, parts)]
        if all(cl):
            s = "、かつ".join([_te(c) for c in cl[:-1]] + [cl[-1]])
            return f"{s}馬{tail}", False
    return f"{name}が「{_r(lv)}」の馬{tail}", True


def describe_combo(tids: list[str], levels: list[str]) -> str:
    """組み合わせ（AND）: 型ごとの文を「、かつ」でつなぐ（「馬」は最後だけ。当日の型には「（当日）」を添える）。
    型・水準は前後の空白を落とす（買いの組は " | " でつながっている）。"""
    cl = []
    for t, lv in zip([x.strip() for x in tids], [x.strip() for x in levels]):
        s, _ = describe(t, lv)
        day = s.endswith("（当日）")
        s = s.removesuffix("（当日）").removesuffix("馬")
        cl.append((s, "（当日）" if day else ""))
    body = "、かつ".join([_te(c) + d for c, d in cl[:-1]] + [cl[-1][0]])
    return f"{body}馬{cl[-1][1]}"


def vocab_from_levels(path) -> dict[str, list[str]]:
    """levels.parquet（python -m src.research.graded.run frame の出力）から、型ごとの水準の語彙を作る。
    data/meta/graded/level_vocab.json の作り直し: python -m src.research.graded.level_text <levels.parquet>"""
    import pandas as pd
    L = pd.read_parquet(path)
    return {c: sorted(map(str, L[c].dropna().unique())) for c in L.columns if not c.startswith("__") and c != "ALL"}


